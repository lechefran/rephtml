package rephtml

import (
	"bytes"
	"strings"
)

// renderedDocumentHTML marks compact HTML produced by HtmlFile.Render.
//
// The formatter below is intentionally scoped to package-rendered documents.
// It is not a public, general-purpose HTML formatter.
type renderedDocumentHTML []byte

// tokenKind classifies a formatter token.
type tokenKind uint8

const (
	tokenText    tokenKind = iota // text content between tags
	tokenStart                    // a start tag
	tokenEnd                      // an end tag
	tokenVoid                     // a void or self-closing tag
	tokenComment                  // an HTML comment
	tokenRaw                      // a whole raw-text element, such as script
)

// htmlToken stores one formatter token.
type htmlToken struct {
	kind tokenKind
	name string
	text string
}

// formatRenderedDocumentHTML returns an indented representation of rephtml output.
//
// This formatter is a small tokenizer over HTML generated by this package. Keep
// it private and use it only for document pretty-printing paths such as
// WriteToFile and RenderFormatted. If this package later needs to format
// arbitrary external HTML, replace this with a real HTML tokenizer first.
//
// Block structure is indented one element per line. Inline content is
// whitespace-sensitive, since a line break between two inline elements renders
// as a space, so each run of inline elements, text and comments is written on
// one line exactly as rendered. Formatting therefore never changes how a page
// displays.
func formatRenderedDocumentHTML(src renderedDocumentHTML) []byte {
	tokens := tokenizeHTML(string(src))
	if len(tokens) == 0 {
		return src
	}

	var buf bytes.Buffer
	indent := 0

	for i := 0; i < len(tokens); {
		if !isInlineToken(tokens[i]) {
			var consumed int
			indent, consumed = writeBlockToken(&buf, indent, tokens[i:])
			i += consumed
			continue
		}

		end := i + 1
		for end < len(tokens) && isInlineToken(tokens[end]) {
			end++
		}
		switch run := trimSpaceTokens(tokens[i:end]); len(run) {
		case 0:
			// Whitespace between block elements does not display.
		case 1:
			indent, _ = writeBlockToken(&buf, indent, run)
		default:
			indent = writeInlineRun(&buf, indent, run)
		}
		i = end
	}

	return buf.Bytes()
}

// writeBlockToken writes the first token on its own line and returns the new
// indent and the number of tokens consumed. An element holding nothing, or
// only single-line text, is written on one line with its end tag.
func writeBlockToken(buf *bytes.Buffer, indent int, tokens []htmlToken) (int, int) {
	token := tokens[0]
	switch token.kind {
	case tokenRaw:
		writeRawBlock(buf, indent, token.name, token.text)
	case tokenStart:
		if len(tokens) > 1 && tokens[1].kind == tokenEnd && tokens[1].name == token.name {
			writeFormattedLine(buf, indent, token.text+tokens[1].text)
			return indent, 2
		}
		if len(tokens) > 2 && tokens[1].kind == tokenText && tokens[2].kind == tokenEnd &&
			tokens[2].name == token.name && !isRawTextElement(token.name) && !strings.Contains(tokens[1].text, "\n") {
			writeFormattedLine(buf, indent, token.text+tokens[1].text+tokens[2].text)
			return indent, 3
		}
		writeFormattedLine(buf, indent, token.text)
		return indent + 1, 1
	case tokenEnd:
		if indent > 0 {
			indent--
		}
		writeFormattedLine(buf, indent, token.text)
	case tokenVoid, tokenComment:
		writeFormattedLine(buf, indent, token.text)
	case tokenText:
		writeFormattedText(buf, indent, token.text)
	}
	return indent, 1
}

// writeInlineRun writes a run of inline tokens on one line, verbatim, and
// returns the new indent.
//
// A run can close inline elements opened before it or leave some open after
// it, when a block element sits inside an inline one. The line is outdented by
// the elements it closes, and the indent afterwards accounts for those it
// leaves open, so the surrounding block structure stays aligned.
func writeInlineRun(buf *bytes.Buffer, indent int, run []htmlToken) int {
	depth, lowest := 0, 0
	var line strings.Builder
	for _, token := range run {
		switch token.kind {
		case tokenStart:
			depth++
		case tokenEnd:
			depth--
			lowest = min(lowest, depth)
		}
		line.WriteString(token.text)
	}
	writeFormattedLine(buf, max(indent+lowest, 0), line.String())
	return max(indent+depth, 0)
}

// trimSpaceTokens drops whitespace-only text from both ends of an inline run.
// At the start or end of a line of content it does not display.
func trimSpaceTokens(run []htmlToken) []htmlToken {
	for len(run) > 0 && isSpaceToken(run[0]) {
		run = run[1:]
	}
	for len(run) > 0 && isSpaceToken(run[len(run)-1]) {
		run = run[:len(run)-1]
	}
	return run
}

// isSpaceToken reports whether a token is text made only of whitespace.
func isSpaceToken(token htmlToken) bool {
	return token.kind == tokenText && strings.TrimSpace(token.text) == ""
}

// isInlineToken reports whether a token is inline content: text, a comment, an
// inline element's tag, or a textarea, which sits inline in a form.
func isInlineToken(token htmlToken) bool {
	switch token.kind {
	case tokenText, tokenComment:
		return true
	case tokenRaw:
		return token.name == "textarea"
	default:
		return isInlineTag(token.name)
	}
}

// isInlineTag reports whether a tag name is an element that displays inline by
// default, so whitespace around it is significant.
func isInlineTag(tag string) bool {
	switch tag {
	case "a", "abbr", "b", "bdi", "bdo", "br", "button", "cite", "code", "data", "del", "dfn",
		"em", "i", "img", "input", "ins", "kbd", "label", "mark", "meter", "output", "progress",
		"q", "rb", "rp", "rt", "rtc", "ruby", "s", "samp", "small", "span", "strong", "sub",
		"sup", "time", "u", "var", "wbr":
		return true
	default:
		return false
	}
}

// tokenizeHTML converts rendered HTML into formatter tokens.
func tokenizeHTML(input string) []htmlToken {
	tokens := []htmlToken{}
	for i := 0; i < len(input); {
		if input[i] != '<' || !isHTMLTagStart(input, i) {
			next := nextHTMLTagStart(input, i+1)
			if next == -1 {
				tokens = appendTextToken(tokens, input[i:])
				break
			}
			tokens = appendTextToken(tokens, input[i:next])
			i = next
			continue
		}

		if strings.HasPrefix(input[i:], "<!--") {
			end := strings.Index(input[i:], "-->")
			if end == -1 {
				tokens = append(tokens, htmlToken{kind: tokenComment, text: input[i:]})
				break
			}
			end += len("-->")
			tokens = append(tokens, htmlToken{kind: tokenComment, text: input[i : i+end]})
			i += end
			continue
		}

		end := findTagEnd(input, i)
		if end == -1 {
			tokens = appendTextToken(tokens, input[i:])
			break
		}

		tag := input[i : end+1]
		name := tagName(tag)
		if name == "" {
			tokens = appendTextToken(tokens, tag)
			i = end + 1
			continue
		}

		switch {
		case isEndTag(tag):
			tokens = append(tokens, htmlToken{kind: tokenEnd, name: name, text: tag})
		case isVoidTag(name) || isSelfClosingTag(tag):
			tokens = append(tokens, htmlToken{kind: tokenVoid, name: name, text: tag})
		default:
			if isRawTextElement(name) {
				rawStart := end + 1
				closeTag := "</" + name + ">"
				// The index has to point into input, so the search folds case
				// per byte. strings.ToLower would not do: it is not
				// length-preserving, so a character such as U+212A KELVIN SIGN
				// earlier in the body would shift the result and truncate the
				// closing tag, leaving the element open for the rest of the
				// document.
				closeAt := indexFold(input[rawStart:], closeTag)
				if closeAt != -1 {
					rawEnd := rawStart + closeAt
					tokens = append(tokens, htmlToken{
						kind: tokenRaw,
						name: name,
						text: input[i : rawEnd+len(closeTag)],
					})
					i = rawEnd + len(closeTag)
					continue
				}
			}
			tokens = append(tokens, htmlToken{kind: tokenStart, name: name, text: tag})
		}

		i = end + 1
	}
	return tokens
}

// appendTextToken appends meaningful text content to the token stream.
func appendTextToken(tokens []htmlToken, text string) []htmlToken {
	if text == "" {
		return tokens
	}
	// Whitespace-only text is kept: between inline elements it displays as a
	// space. The formatter drops it where it does not display.
	return append(tokens, htmlToken{kind: tokenText, text: text})
}

// writeFormattedLine writes one indented formatter line.
func writeFormattedLine(buf *bytes.Buffer, indent int, line string) {
	buf.WriteString(tabs(indent))
	buf.WriteString(line)
	buf.WriteByte('\n')
}

// writeFormattedText writes formatted text lines.
func writeFormattedText(buf *bytes.Buffer, indent int, text string) {
	for _, line := range strings.Split(text, "\n") {
		if line == "" {
			continue
		}
		writeFormattedLine(buf, indent, line)
	}
}

// writeRawBlock writes raw-text elements without corrupting sensitive content.
func writeRawBlock(buf *bytes.Buffer, indent int, name, text string) {
	if name == "style" {
		if openTag, body, closeTag, ok := splitRawElement(text, name); ok {
			writeFormattedLine(buf, indent, openTag)
			writeIndentedRawLines(buf, indent+1, body)
			writeFormattedLine(buf, indent, closeTag)
			return
		}
	}

	buf.WriteString(tabs(indent))
	buf.WriteString(text)
	if !strings.HasSuffix(text, "\n") {
		buf.WriteByte('\n')
	}
}

// splitRawElement separates a raw-text element into open tag, body, and close tag.
func splitRawElement(text, name string) (string, string, string, bool) {
	openEnd := findTagEnd(text, 0)
	if openEnd == -1 {
		return "", "", "", false
	}

	closeTag := "</" + name + ">"
	// Folded per byte so the index stays valid in text; see tokenizeHTML.
	closeAt := lastIndexFold(text, closeTag)
	if closeAt == -1 || closeAt < openEnd {
		return "", "", "", false
	}

	return text[:openEnd+1], text[openEnd+1 : closeAt], text[closeAt:], true
}

// writeIndentedRawLines writes raw block body lines under the current indent.
func writeIndentedRawLines(buf *bytes.Buffer, indent int, text string) {
	text = strings.Trim(text, "\n")
	if text == "" {
		return
	}

	for _, line := range strings.Split(text, "\n") {
		if strings.TrimSpace(line) == "" {
			buf.WriteByte('\n')
			continue
		}
		writeFormattedLine(buf, indent, line)
	}
}

// tagName extracts the lower-case element name from an HTML tag.
func tagName(tag string) string {
	tag = strings.TrimSpace(tag)
	tag = strings.TrimPrefix(tag, "<")
	tag = strings.TrimPrefix(tag, "/")
	tag = strings.TrimSuffix(tag, ">")
	tag = strings.TrimSpace(tag)
	if tag == "" || strings.HasPrefix(tag, "!") {
		return ""
	}
	if idx := strings.IndexAny(tag, " \t\r\n/"); idx != -1 {
		tag = tag[:idx]
	}
	return strings.ToLower(tag)
}

// isEndTag reports whether a tag is a closing tag.
func isEndTag(tag string) bool {
	return strings.HasPrefix(strings.TrimSpace(tag), "</")
}

// isSelfClosingTag reports whether a tag ends with a self-closing slash.
func isSelfClosingTag(tag string) bool {
	tag = strings.TrimSpace(tag)
	tag = strings.TrimSuffix(tag, ">")
	return strings.HasSuffix(strings.TrimSpace(tag), "/")
}

// isVoidTag reports whether a tag name is an HTML void element.
func isVoidTag(tag string) bool {
	switch tag {
	case "area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "source", "track", "wbr":
		return true
	default:
		return false
	}
}

// isRawTextElement reports whether a tag body needs raw-text handling.
func isRawTextElement(tag string) bool {
	switch tag {
	case "script", "style", "pre", "textarea":
		return true
	default:
		return false
	}
}

// nextHTMLTagStart returns the next likely HTML tag start position.
func nextHTMLTagStart(input string, from int) int {
	for i := from; i < len(input); i++ {
		if input[i] == '<' && isHTMLTagStart(input, i) {
			return i
		}
	}
	return -1
}

// isHTMLTagStart reports whether a less-than sign starts likely HTML markup.
func isHTMLTagStart(input string, idx int) bool {
	if idx+1 >= len(input) || input[idx] != '<' {
		return false
	}
	if strings.HasPrefix(input[idx:], "<!--") {
		return true
	}

	next := input[idx+1]
	if next == '/' {
		return idx+2 < len(input) && isTagNameStart(input[idx+2])
	}
	if next == '!' {
		return hasPrefixFold(input[idx:], "<!doctype")
	}
	return isTagNameStart(next)
}

// isTagNameStart reports whether a byte can start an HTML tag name.
func isTagNameStart(c byte) bool {
	return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z')
}

// findTagEnd returns the closing greater-than sign while respecting quotes.
func findTagEnd(input string, start int) int {
	var quote byte
	for i := start + 1; i < len(input); i++ {
		c := input[i]
		if quote != 0 {
			if c == quote {
				quote = 0
			}
			continue
		}
		switch c {
		case '\'', '"':
			quote = c
		case '>':
			return i
		}
	}
	return -1
}
